-- صيغة المتغير الجديدة في نص القالب: #Var1# بدلاً من {{1}}
-- (التطبيق يقبل الصيغة القديمة ويحوّلها أيضاً، وهذا يوحّد النصوص المحفوظة سابقاً)
UPDATE "template_requests"
SET "content" = regexp_replace("content", '\{\{\s*([0-9]{1,3})\s*\}\}', '#Var\1#', 'g')
WHERE "content" ~ '\{\{\s*[0-9]{1,3}\s*\}\}';
